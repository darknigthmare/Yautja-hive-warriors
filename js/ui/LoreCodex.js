const PROVENANCE_LABELS = Object.freeze({
  reference: 'Repère d’œuvre',
  adaptation: 'Règle du jeu',
  'reference-and-adaptation': 'Œuvre et adaptation du jeu'
});

export class LoreCodexManager {
  constructor() {
    this.modal = document.getElementById('codex-modal');
    this.contentBox = document.getElementById('codex-content-container');
    this.activeTab = 'ranks';
    this.setupListeners();
  }

  setupListeners() {
    const btnOpen = document.getElementById('btn-open-codex');
    if (btnOpen) {
      btnOpen.addEventListener('click', () => this.open());
    }

    const btnClose = document.getElementById('btn-close-codex');
    if (btnClose) {
      btnClose.addEventListener('click', () => this.close());
    }

    document.querySelectorAll('.codex-tab-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        document.querySelectorAll('.codex-tab-btn').forEach(b => { b.classList.remove('active'); b.setAttribute('aria-pressed', 'false'); });
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
        this.activeTab = btn.dataset.tab;
        this.renderTabContent();
      });
    });
  }

  open() {
    this.renderTabContent();
    if (this.modal) {
      if (window.game?.ui) window.game.ui.showScreen(this.modal);
      else this.modal.classList.remove('hidden');
    }
  }

  close() {
    if (window.game?.ui) window.game.ui.showScreen(window.game.ui.mainMenu);
    else if (this.modal) this.modal.classList.add('hidden');
  }

  renderTabContent() {
    if (!this.contentBox) return;
    this.contentBox.innerHTML = '';

    const list = LORE_ENTRIES[this.activeTab] || [];
    list.forEach(item => {
      const card = document.createElement('div');
      card.className = 'codex-entry-card';

      const title = document.createElement('h3');
      title.innerText = item.title;
      card.appendChild(title);

      const context = document.createElement('p');
      context.className = 'codex-entry-context';
      context.textContent = `${PROVENANCE_LABELS[item.provenance]} · ${item.scope}`;
      card.appendChild(context);

      const desc = document.createElement('p');
      desc.innerText = item.desc;
      card.appendChild(desc);

      if (item.sourceIds?.length) {
        const references = document.createElement('p');
        references.className = 'codex-entry-sources';
        references.appendChild(document.createTextNode('Sources : '));
        item.sourceIds.forEach((sourceId, index) => {
          const source = LORE_SOURCES[sourceId];
          if (index) references.appendChild(document.createTextNode(' · '));
          const link = document.createElement('a');
          link.href = source.url;
          link.textContent = source.label;
          link.title = `${source.title} — ${source.type}`;
          link.target = '_blank';
          link.rel = 'noopener noreferrer';
          references.appendChild(link);
        });
        card.appendChild(references);
      }

      this.contentBox.appendChild(card);
    });
  }
}

// Reproduce the browser catalogue from the preserved PR #3 audit.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('docs/audits/2026-10-26/audit-data.json', root), 'utf8');
const audit = JSON.parse(source);
const rows = name => audit.sheets.find(sheet => sheet.name === name).rows;
const pick = (row, keys) => Object.fromEntries(keys.filter(key => row[key] !== undefined).map(key => [key, row[key]]));
const data = {
  provenance: { auditCommit: '0435827e41eae19472179e8116d9eb4105647664', codeSnapshot: audit.meta.commit,
    auditDate: audit.meta.asOf, auditSha256: createHash('sha256').update(source).digest('hex'),
    dimensions: 'game units; proposed design envelopes, not measured film geometry', visualFidelity1to1Verified: false },
  profiles: rows('Bestiaire_medias').map(row => pick(row, ['id', 'faction', 'name', 'kind', 'spawnEligibility', 'work', 'medium', 'continuity', 'evidenceStatus', 'evidenceFact', 'sourceIds', 'codeStatus', 'missingWork', 'combatRole', 'groupRule', 'allowedMatchups', 'compatiblePlaces', 'restrictions', 'priority'])),
  maps: rows('Cartes_zones'), operations: rows('Affrontements'), groups: rows('Groupes'),
  budgets: audit.budget.rows, fronts: rows('Fronts'), bosses: rows('Boss_et_elites'),
  fidelityRules: rows('Fidelite'), mediaPlaces: rows('Lieux_medias'),
  sources: audit.mediaSources.map(row => pick(row, ['id', 'title', 'url', 'publisher', 'type', 'scope', 'accessed'])),
};
const output = '// Generated by scripts/sync-battle-catalog.mjs from the preserved PR #3 audit.\n'
  + '// These are sourced profiles and proposed operations, not certified rendered assets.\n'
  + 'export const BATTLE_CATALOG_DATA = ' + JSON.stringify(data, null, 2) + ';\n';
const target = new URL('js/data/BattleCatalogData.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Battle catalogue differs from its preserved audit source');
} else await writeFile(target, output);
console.log(JSON.stringify({ status: 'passed', profiles: data.profiles.length, maps: data.maps.length,
  operations: data.operations.length, groups: data.groups.length, budgets: data.budgets.length,
  fronts: data.fronts.length, sources: data.sources.length, auditSha256: data.provenance.auditSha256 }));
